CREATE TABLE IF NOT EXISTS predictions (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    prediction_date DATE NOT NULL,
    target_date DATE NOT NULL,
    sector TEXT NOT NULL,
    ticker TEXT NOT NULL,
    company_name TEXT NOT NULL,
    selected_price DOUBLE PRECISION NOT NULL,
    model_score DOUBLE PRECISION NOT NULL,
    signal TEXT NOT NULL,
    prediction TEXT NOT NULL,
    confidence INTEGER NOT NULL,
    candidate_scores JSONB NOT NULL,
    data_snapshot JSONB NOT NULL,
    result_status TEXT DEFAULT 'Pending',
    result_return DOUBLE PRECISION,
    result_price DOUBLE PRECISION,
    UNIQUE(prediction_date, sector)
);

CREATE TABLE IF NOT EXISTS daily_forecasts (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    prediction_date DATE NOT NULL,
    forecast_date DATE NOT NULL,
    horizon_days INTEGER NOT NULL,
    sector TEXT NOT NULL,
    ticker TEXT NOT NULL,
    company_name TEXT NOT NULL,
    starting_price DOUBLE PRECISION NOT NULL,
    predicted_direction TEXT NOT NULL,
    confidence INTEGER NOT NULL,
    model_score DOUBLE PRECISION NOT NULL,
    actual_direction TEXT DEFAULT 'Pending',
    actual_return DOUBLE PRECISION,
    actual_price DOUBLE PRECISION,
    result_status TEXT DEFAULT 'Pending',
    UNIQUE(prediction_date, forecast_date, sector, ticker)
);
